"""HarnessLens: inspect app-side state and analytics recorded in NDJSON."""
from __future__ import annotations
import argparse
import datetime as dt
import json
import sys
import tempfile
import time
import uuid
from pathlib import Path

from .device import Device, DeviceError
from .model import EvidenceError, parse_evidence, read_file, state_get, state_history, field_value, analytics_events, state_contract
from . import analytics_contract
from .wiremock import add_parser as add_wiremock_parser, dispatch as dispatch_wiremock


def display(value: object) -> None:
    print(json.dumps(value, indent=2, ensure_ascii=False))


def add_device(parser: argparse.ArgumentParser, *, required: bool = True) -> None:
    parser.add_argument("--platform", choices=["android", "ios"], required=required)
    parser.add_argument("--app-id", required=required, help="Android package or iOS bundle identifier")
    parser.add_argument("--device-id", help="ADB device serial or iOS simulator UDID")


def add_source(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--file", type=Path, help="Previously exported NDJSON; otherwise read from device")
    parser.add_argument("--platform", choices=["android", "ios"])
    parser.add_argument("--app-id")
    parser.add_argument("--device-id")
    parser.add_argument("--run-id", help="Run to read; default is device control.json run_id")


def source(args: argparse.Namespace) -> list[dict]:
    if args.file:
        return read_file(args.file, expected_run=args.run_id)
    if not args.platform or not args.app_id:
        raise EvidenceError("Specify --file or both --platform and --app-id")
    device = Device(args.platform, args.app_id, args.device_id)
    run_id = args.run_id or device.read_control().get("run_id")
    if not run_id:
        raise EvidenceError("No run_id in control.json: run `hlens capture start` first")
    return parse_evidence(device.read_capture(run_id), expected_run=run_id)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="hlens", description="HarnessLens local Android/iOS evidence CLI")
    sub = p.add_subparsers(dest="group", required=True)
    capture = sub.add_parser("capture", help="Start/stop/export/read a device capture")
    capsub = capture.add_subparsers(dest="command", required=True)
    for name in ("start", "stop", "status", "export"):
        cmd = capsub.add_parser(name)
        add_device(cmd)
        if name == "stop":
            cmd.add_argument("--settle", type=float, default=0.5, help="Best-effort time to let the app recorder drain queued writes before disarming")
        if name == "export":
            cmd.add_argument("--out", required=True, type=Path)
            cmd.add_argument("--run-id")
        if name == "start":
            cmd.add_argument("--run-id", help="Custom ID (32 hex chars); generated by default")
    state = sub.add_parser("state", help="Read state, history, await or verify")
    statesub = state.add_subparsers(dest="command", required=True)
    for name in ("get", "history", "await", "verify"):
        cmd = statesub.add_parser(name)
        add_source(cmd)
        if name in ("get", "history", "await"):
            cmd.add_argument("--scope", required=True)
        if name == "await":
            cmd.add_argument("--field", required=True)
            cmd.add_argument("--equals", required=True, help="JSON literal, e.g. 'true' or '"+'"confirmed"'+'"'+'; unquoted text interpreted as string')
            cmd.add_argument("--timeout", type=float, default=20)
            cmd.add_argument("--interval", type=float, default=0.5)
        if name == "verify":
            cmd.add_argument("--contract", type=Path, required=True)
            cmd.add_argument("--out", type=Path)
    analytics = sub.add_parser("analytics", help="Inspect or verify analytics events")
    anasub = analytics.add_subparsers(dest="command", required=True)
    for name in ("events", "verify"):
        cmd = anasub.add_parser(name)
        add_source(cmd)
        if name == "verify":
            cmd.add_argument("--contract", type=Path, required=True)
            cmd.add_argument("--report-dir", type=Path, required=True)
    add_wiremock_parser(sub)
    args = p.parse_args(argv)
    try:
        return dispatch(args)
    except (DeviceError, EvidenceError) as exc:
        print(f"INCONCLUSIVE: {exc}", file=sys.stderr)
        return 2
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"INVALID_INPUT: {exc}", file=sys.stderr)
        return 3
    except KeyboardInterrupt:
        return 130


def dispatch(args: argparse.Namespace) -> int:
    if args.group == "mock":
        return dispatch_wiremock(args)
    if args.group == "capture":
        device = Device(args.platform, args.app_id, args.device_id)
        if args.command == "start":
            run_id = args.run_id or uuid.uuid4().hex
            if len(run_id) != 32 or any(ch not in "0123456789abcdef" for ch in run_id):
                raise ValueError("run_id must be 32 lowercase hexadecimal characters")
            device.write_control({"version": 1, "run_id": run_id, "active": True,
                                  "started_at": dt.datetime.now(dt.timezone.utc).isoformat()})
            display({"status": "ARMED", "run_id": run_id, "note": "Launch/interact with app; SDK emits capture_ready on its next recorded call"})
            return 0
        doc = device.read_control()
        run_id = getattr(args, "run_id", None) or doc.get("run_id")
        if not run_id:
            raise EvidenceError("No current run ID")
        if args.command == "stop":
            time.sleep(max(0.0, min(args.settle, 5.0)))
            doc["active"] = False
            doc["stopped_at"] = dt.datetime.now(dt.timezone.utc).isoformat()
            device.write_control(doc)
            display({"status": "STOPPED", "run_id": run_id})
            return 0
        if args.command in ("status", "export"):
            try:
                data = device.read_capture(run_id)
                records = parse_evidence(data, expected_run=run_id)
            except (DeviceError, EvidenceError) as exc:
                display({"status": "INCONCLUSIVE", "run_id": run_id, "active": doc.get("active"), "reason": str(exc)})
                return 2
            if args.command == "export":
                args.out.parent.mkdir(parents=True, exist_ok=True)
                args.out.write_bytes(data)
                display({"status": "EXPORTED", "out": str(args.out), "run_id": run_id, "record_count": len(records)})
            else:
                display({"status": "READY", "active": doc.get("active"), "run_id": run_id,
                         "events": len(analytics_events(records)),
                         "states": sum(r["type"] == "state" for r in records)})
            return 0
    if args.group == "state" and args.command == "await":
        deadline = time.monotonic() + max(0, args.timeout)
        try:
            expected = json.loads(args.equals)
        except ValueError:
            expected = args.equals
        last = None
        missing = False
        while True:
            try:
                value = field_value(state_get(source(args), args.scope)["values"], args.field)
                last = value
                missing = False
                if type(value) is type(expected) and value == expected:
                    display({"status": "PASS", "scope": args.scope, "field": args.field, "actual": value})
                    return 0
            except (EvidenceError, DeviceError) as exc:
                last = f"unavailable: {exc}"
                missing = True
            if time.monotonic() >= deadline:
                display({"status": "INCONCLUSIVE" if missing else "FAIL",
                         "scope": args.scope, "field": args.field, "expected": expected, "last": last})
                return 2 if missing else 1
            time.sleep(max(0.1, args.interval))
    records = source(args)
    if args.group == "state":
        if args.command == "get":
            display(state_get(records, args.scope))
        elif args.command == "history":
            display(state_history(records, args.scope))
        elif args.command == "verify":
            contract = json.loads(args.contract.read_text())
            report = state_contract(contract, records)
            if args.out:
                args.out.parent.mkdir(parents=True, exist_ok=True)
                args.out.write_text(json.dumps(report, indent=2) + "\n")
            display(report)
            return {"PASS": 0, "FAIL": 1, "INCONCLUSIVE": 2}[report["status"]]
        return 0
    if args.group == "analytics":
        if args.command == "events":
            display(analytics_events(records))
            return 0
        # A healthy *state* recorder does not prove analytics instrumentation is installed.
        # Until at least one analytics event is present, absence is inconclusive.
        events = analytics_events(records)
        contract = analytics_contract.load_contract(args.contract)
        if not events:
            report = {
                "schema_version": 1,
                "scenario": contract["scenario"],
                "status": "INCONCLUSIVE",
                "reason": "No analytics events captured; cannot distinguish absent instrumentation from missing events",
                "event_count": 0,
            }
            args.report_dir.mkdir(parents=True, exist_ok=True)
            (args.report_dir / "report.json").write_text(json.dumps(report, indent=2) + "\n")
            (args.report_dir / "report.md").write_text("# Analytics contract\n\n**INCONCLUSIVE:** " + report["reason"] + "\n")
            display({"status": "INCONCLUSIVE", "report_dir": str(args.report_dir), "events": 0})
            return 2
        # Reuse the previously built Analytics Event Validator contract semantics.
        # That validator intentionally handles only analytics record types.
        with tempfile.TemporaryDirectory(prefix="hlens-") as td:
            path = Path(td) / "events.ndjson"
            filtered = [r for r in records if r["type"] in ("capture_ready", "event")]
            path.write_text("".join(json.dumps(r) + "\n" for r in filtered))
            report = analytics_contract.evaluate(contract, path)
        args.report_dir.mkdir(parents=True, exist_ok=True)
        (args.report_dir / "report.json").write_text(json.dumps(report, indent=2) + "\n")
        (args.report_dir / "report.md").write_text(analytics_contract.render_markdown(report))
        display({"status": report["status"], "report_dir": str(args.report_dir), "events": report["event_count"]})
        return {"PASS": 0, "FAIL": 1, "INCONCLUSIVE": 2}[report["status"]]
    return 3


if __name__ == "__main__":
    sys.exit(main())
